// Удобная запись: «|» отмечает каретку, «...» — выделение. Скобки для выделения намеренно НЕ
// квадратные: в самом markdown их полно ("- [x]", "[текст](url)"), и разметка теста коллизировала
// бы с разметкой, которую тест проверяет.
function parse(spec) {
  if (spec.includes("\u00AB")) {
    const a = spec.indexOf("\u00AB");
    const rest = spec.slice(0, a) + spec.slice(a + 1);
    const b = rest.indexOf("\u00BB");
    return { text: rest.slice(0, b) + rest.slice(b + 1), start: a, end: b };
  }
  const a = spec.indexOf("|");
  return { text: spec.slice(0, a) + spec.slice(a + 1), start: a, end: a };
}
function render(text, selStart, selEnd) {
  if (selStart === selEnd) return text.slice(0, selStart) + "|" + text.slice(selStart);
  return text.slice(0, selStart) + "\u00AB" + text.slice(selStart, selEnd) + "\u00BB" + text.slice(selEnd);
}
function run(spec, action) {
  const { text, start, end } = parse(spec);
  const res = E.applyMarkdownAction(text, start, end, action);
  if (!res) return null;
  const next = text.slice(0, res.from) + res.insert + text.slice(res.to);
  return render(next, res.selStart, res.selEnd);
}

