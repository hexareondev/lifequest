/* --- Продолжение списка по Enter --- */
function enter(spec) {
  const { text, start } = parse(spec);
  const res = E.continueListOnEnter(text, start);
  if (!res) return null;
  const next = text.slice(0, res.from) + res.insert + text.slice(res.to);
  return render(next, res.selStart, res.selEnd);
}
eq("Enter продолжает маркированный список", enter("- раз|"), "- раз\n- |");
eq("Enter продолжает нумерацию со следующего числа", enter("2. два|"), "2. два\n3. |");
eq("Enter продолжает список дел неотмеченным пунктом", enter("- [x] дело|"), "- [x] дело\n- [ ] |");
eq("отступ вложенного пункта переносится", enter("  - раз|"), "  - раз\n  - |");
eq("Enter на пустом пункте выходит из списка", enter("- раз\n- |"), "- раз\n|");
eq("вне списка Enter не перехватывается", enter("обычный текст|"), null);
eq("на пустой строке ничего не происходит", enter("|"), null);

/* --- Сквозная проверка: то, что ставит кнопка, движок разметки обязан понимать. Без неё панель
       и парсер могут разойтись незаметно — кнопка что-то вставит, а в просмотре это останется
       обычным текстом. --- */
function applyTo(text, start, end, action) {
  const r = E.applyMarkdownAction(text, start, end, action);
  return text.slice(0, r.from) + r.insert + text.slice(r.to);
}
function inlineKinds(text) {
  return E.parseInline(text).filter(p => typeof p !== "string").map(p => p.t);
}
eq("жирный читается движком как жирный", inlineKinds(applyTo("слово", 0, 5, "bold")), ["b"]);
eq("курсив читается как курсив",         inlineKinds(applyTo("слово", 0, 5, "italic")), ["i"]);
eq("зачёркнутый читается как зачёркнутый", inlineKinds(applyTo("слово", 0, 5, "strike")), ["s"]);
eq("маркер читается как маркер",         inlineKinds(applyTo("слово", 0, 5, "mark")), ["mark"]);
eq("код читается как код",               inlineKinds(applyTo("слово", 0, 5, "code")), ["code"]);
eq("ссылка на заметку читается как вики-ссылка", inlineKinds(applyTo("Идея", 0, 4, "wiki")), ["wiki"]);

const blockOf = (text) => E.parseMarkdown(text)[0];
