const E = require("./notes_env.js");
const { eq, done } = E;

const types = t => E.parseMarkdown(t).map(b => b.type);

/* --- Блоки --- */
eq("заголовки по уровням", E.parseMarkdown("# А\n## Б\n###### Е").map(b => b.level), [1, 2, 6]);
eq("решётка без пробела заголовком не становится", types("#тег в начале"), ["p"]);
eq("горизонтальная линия", types("---"), ["hr"]);
eq("пункт списка из дефиса линией не становится", types("- пункт"), ["ul"]);
eq("цитата", types("> мысль"), ["quote"]);
eq("код в тройных кавычках", types("```js\nconst a = 1;\n```"), ["code"]);
eq("язык блока кода запоминается", E.parseMarkdown("```python\nx\n```")[0].lang, "python");
eq("внутри блока кода разметка не разбирается",
  E.parseMarkdown("```\n# не заголовок\n- не список\n```")[0].lines, ["# не заголовок", "- не список"]);
eq("незакрытый блок кода не теряется", types("```\nхвост"), ["code"]);

eq("маркированный список", E.parseMarkdown("- раз\n- два")[0].items.map(i => i.text), ["раз", "два"]);
eq("нумерованный список", E.parseMarkdown("1. раз\n2. два")[0].type, "ol");
eq("нумерация начинается со своего числа", E.parseMarkdown("3. раз")[0].start, 3);
eq("вложенность списка по отступу", E.parseMarkdown("- раз\n  - два\n    - три")[0].items.map(i => i.depth), [0, 1, 2]);
eq("смена типа списка разрывает блок", types("- раз\n1. два"), ["ul", "ol"]);

eq("чекбоксы отдельным типом", E.parseMarkdown("- [ ] дело\n- [x] сделано")[0].type, "todo");
eq("состояние чекбоксов", E.parseMarkdown("- [ ] дело\n- [x] сделано")[0].items.map(i => i.checked), [false, true]);
eq("заглавная X тоже отмечена", E.parseMarkdown("- [X] да")[0].items[0].checked, true);

eq("соседние строки склеиваются в абзац", E.parseMarkdown("одна\nдве").length, 1);
eq("пустая строка разделяет абзацы", types("одна\n\nдве"), ["p", "blank", "p"]);
eq("пустой текст даёт пустой разбор", E.parseMarkdown(""), []);

/* Номера строк нужны для переключения чекбоксов — проверяем, что они настоящие */
eq("номер строки у чекбокса соответствует исходнику",
  E.parseMarkdown("текст\n\n- [ ] дело").find(b => b.type === "todo").items[0].line, 2);

/* --- Строчная разметка --- */
const inl = t => E.parseInline(t).map(p => (typeof p === "string" ? p : p.t + ":" + p.v));
eq("жирный", inl("а **б** в"), ["а ", "b:б", " в"]);
eq("курсив звёздочкой", inl("*к*"), ["i:к"]);
eq("курсив подчёркиванием", inl("_к_"), ["i:к"]);
eq("двойное подчёркивание — жирный, а не два курсива", inl("__ж__"), ["b:ж"]);
eq("зачёркнутый", inl("~~нет~~"), ["s:нет"]);
eq("выделение маркером", inl("==важно=="), ["mark:важно"]);
eq("строчный код", inl("`x = 1`"), ["code:x = 1"]);
eq("внутри строчного кода разметка не разбирается", E.parseInline("`**не жирный**`")[0].v, "**не жирный**");
eq("ссылка markdown", E.parseInline("[текст](https://a.b)")[0].v, "https://a.b");
eq("подпись ссылки", E.parseInline("[текст](https://a.b)")[0].label, "текст");
eq("голый адрес становится ссылкой", E.parseInline("см. https://a.b/c")[1].t, "link");
eq("вики-ссылка", E.parseInline("[[Другая заметка]]")[0].v, "Другая заметка");
eq("вики-ссылка со своей подписью", E.parseInline("[[Заметка|как назвать]]")[0].label, "как назвать");
eq("тег строчный", inl("текст #идеи"), ["текст ", "tag:идеи"]);
eq("решётка в середине слова тегом не становится", inl("C#"), ["C#"]);
eq("номер тегом не становится", inl("задача #12"), ["задача #12"]);
eq("жирный имеет приоритет над курсивом", E.parseInline("**жир**")[0].t, "b");

/* --- Переключение чекбокса --- */
const src = "заметка\n\n- [ ] первое\n- [x] второе\n\nхвост";
const on = E.toggleMarkdownCheckbox(src, 2);
eq("отметка ставится в нужной строке", on.split("\n")[2], "- [x] первое");
eq("остальные строки не тронуты", on.split("\n")[3], "- [x] второе");
eq("снятие отметки", E.toggleMarkdownCheckbox(src, 3).split("\n")[3], "- [ ] второе");
eq("двойное переключение возвращает исходник", E.toggleMarkdownCheckbox(on, 2), src);
eq("отступ перед пунктом сохраняется",
  E.toggleMarkdownCheckbox("  - [ ] вложенное", 0), "  - [x] вложенное");
eq("строка без чекбокса не меняется", E.toggleMarkdownCheckbox(src, 0), src);
eq("номер за границей текста не роняет", E.toggleMarkdownCheckbox(src, 99), src);

/* --- Разметка не может исполниться: проверяем, что HTML остаётся текстом --- */
const evil = E.parseMarkdown("<script>alert(1)</script>");
eq("HTML разбирается как обычный абзац", evil[0].type, "p");
eq("HTML остаётся текстом, а не узлом разметки", E.parseInline(evil[0].text).every(p => typeof p === "string"), true);

done();
