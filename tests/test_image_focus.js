/* Точка кадрирования: object-cover обрезает по краям, и без неё у портрета вместо лица
   оказывается шея. Значение приходит из интерфейса, из старых сохранений и из чужого бэкапа,
   поэтому проверяем в первую очередь устойчивость к мусору. */
const E = require("./notes_env.js");
const { eq, done } = E;

eq("обычная точка проходит как есть", E.imagePosOf({ x: 30, y: 20 }), { x: 30, y: 20 });
eq("нули — законное значение, а не пустота", E.imagePosOf({ x: 0, y: 0 }), { x: 0, y: 0 });
eq("края допустимы", E.imagePosOf({ x: 100, y: 100 }), { x: 100, y: 100 });
eq("выход за границы подрезается", E.imagePosOf({ x: 150, y: -20 }), { x: 100, y: 0 });
eq("дробные значения сохраняются", E.imagePosOf({ x: 33.5, y: 66.5 }), { x: 33.5, y: 66.5 });

eq("нет точки — центр", E.imagePosOf(null), { x: 50, y: 50 });
eq("пустой объект — центр", E.imagePosOf({}), { x: 50, y: 50 });
eq("половина точки — вторая координата по центру", E.imagePosOf({ x: 10 }), { x: 10, y: 50 });
eq("строки не принимаются", E.imagePosOf({ x: "10", y: "20" }), { x: 50, y: 50 });
eq("NaN не протекает", E.imagePosOf({ x: NaN, y: 10 }), { x: 50, y: 10 });
eq("бесконечность не протекает", E.imagePosOf({ x: Infinity, y: 10 }), { x: 50, y: 10 });

/* Центр — это и есть поведение по умолчанию, лишний стиль на каждую картинку не нужен */
eq("центр не даёт стиля", E.imagePosStyle(null), undefined);
eq("явный центр тоже не даёт стиля", E.imagePosStyle({ x: 50, y: 50 }), undefined);
eq("смещение даёт objectPosition", E.imagePosStyle({ x: 30, y: 20 }), { objectPosition: "30% 20%" });
eq("подрезанное значение попадает в стиль", E.imagePosStyle({ x: 999, y: 0 }), { objectPosition: "100% 0%" });
eq("мусор не даёт стиля", E.imagePosStyle({ x: "нет" }), undefined);

/* Точку легко задать и забыть применить в одном из мест показа — так и вышло с предпросмотром в
   форме. Правило простое и проверяемое по исходнику: если рисуется СОХРАНЁННАЯ картинка
   (coverImage / avatarImage), рядом обязан стоять imagePosStyle. Картинки, ещё не выбранные
   (черновик ссылки, результаты поиска), под правило не подпадают — у них точки просто нет. */
const src = E.rawSource;
const offenders = src.split("\n")
  .map((line, i) => ({ line: line.trim(), n: i + 1 }))
  .filter(x => /<img[^>]*src=\{[^}]*(coverImage|avatarImage)/.test(x.line))
  .filter(x => !/imagePosStyle/.test(x.line))
  .map(x => x.n);
eq("сохранённые картинки везде рисуются с точкой кадрирования", offenders, []);

done();
