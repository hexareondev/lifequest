// Точка кадрирования картинки — общая механика обложек и аватаров, поэтому лежит в core, а не в
// библиотеке: карточка человека пользуется ей ровно так же, как карточка книги.

import { clamp } from "./basics.js";

// Точка кадрирования картинки, в процентах от её ширины и высоты. object-cover обрезает лишнее
// по краям и по умолчанию показывает центр — у книжного постера там середина обложки, а у
// портрета вместо лица оказывается шея. Хранится на самом объекте, а не в настройках: у каждой
// картинки своё удачное место.
export function imagePosOf(pos) {
  const num = (v) => (typeof v === "number" && isFinite(v) ? clamp(v, 0, 100) : 50);
  return { x: num(pos && pos.x), y: num(pos && pos.y) };
}
// Ровно центр — это и есть поведение по умолчанию, отдельного стиля для него не нужно.
export function imagePosStyle(pos) {
  const p = imagePosOf(pos);
  return p.x === 50 && p.y === 50 ? undefined : { objectPosition: `${p.x}% ${p.y}%` };
}
